import { mkdir, writeFile } from "node:fs/promises";
import { openSync } from "fontkit";
import sharp from "sharp";
import { rayEnd, riftGeometry as shape } from "../src/lib/brand-geometry.ts";

const font = openSync(
  "node_modules/@fontsource/geist/files/geist-latin-700-normal.woff",
);
function outline(text, size, tracking = 0) {
  const run = font.layout(text);
  const scale = size / font.unitsPerEm;
  let cursor = 0;
  const paths = run.glyphs.map((glyph, i) => {
    const position = run.positions[i];
    const path = {
      d: glyph.path.toSVG(),
      x: +(cursor + position.xOffset * scale).toFixed(3),
      y: +(position.yOffset * scale).toFixed(3),
    };
    cursor += position.xAdvance * scale + tracking;
    return path;
  });
  return { paths, width: +(cursor - tracking).toFixed(3), scale };
}
const word = outline("WireRift", 64, -1.4);
const tagline = outline("LOCALHOST TO THE WORLD", 15, 0.5);
const glyphs = (data, baseline) =>
  data.paths
    .map(
      (p) =>
        `<path d="${p.d}" transform="translate(${p.x} ${baseline - p.y}) scale(${data.scale} ${-data.scale})"/>`,
    )
    .join("");
const wordArt = glyphs(word, 51);

await mkdir("public", { recursive: true });
await writeFile(
  "src/lib/wordmark.ts",
  `// Generated by scripts/brand.mjs from Geist (OFL). Do not edit by hand.\nexport const wordmark = ${JSON.stringify(word)} as const;\n`,
);

function symbol(cut, compact = false) {
  const rays = compact
    ? shape.rays.filter((_, i) => i === 0 || i === 3 || i === 4)
    : shape.rays;
  const wires = shape.wires
    .map(
      (d) =>
        `<path d="${d}" fill="currentColor" stroke="${cut}" stroke-width="3.2" stroke-linejoin="round" paint-order="stroke"/>`,
    )
    .join("");
  const signals = rays
    .map((p) => {
      const end = rayEnd(p);
      return `<path d="M${p.x} ${p.y} ${p.ex} ${p.ey}" stroke="#F5AD21"/><path d="M${p.x} ${p.y} ${end.x} ${end.y}"/><circle cx="${p.ex}" cy="${p.ey}" r="${p.r}" fill="${end.outer ? "#F5AD21" : cut}" stroke="none"/>`;
    })
    .join("");
  const detail = compact
    ? ""
    : `<path d="${shape.arrow}" stroke-linecap="butt" fill="#F5AD21" stroke="#F5AD21"/>${shape.sparks.map((p) => `<circle cx="${p.cx}" cy="${p.cy}" r="${p.r}" stroke="none"/>`).join("")}`;
  return `<circle cx="64" cy="60" r="44" fill="#F5AD21"/>${wires}<g fill="${cut}" stroke="${cut}" stroke-width="2.2" stroke-linecap="round">${signals}${detail}</g><path d="${shape.bolt}" fill="currentColor" stroke="${cut}" stroke-width="3.8" stroke-linejoin="miter" paint-order="stroke"/>`;
}
const svg = (viewBox, ink, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="none" color="${ink}"><title>WireRift</title>${body}</svg>`;
const mark = (ink, cut, compact = false) =>
  svg("0 0 128 128", ink, symbol(cut, compact));
function stacked(cut) {
  return `<g transform="translate(95 8) scale(1.65)">${symbol(cut)}</g><g transform="translate(${(400 - word.width) / 2} 213)" fill="currentColor">${wordArt}</g><g transform="translate(${(400 - tagline.width) / 2} 273)" fill="currentColor">${glyphs(tagline, 15)}</g>`;
}
